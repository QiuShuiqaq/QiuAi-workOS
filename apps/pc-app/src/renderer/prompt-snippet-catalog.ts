export type PromptSnippetCategory = (typeof promptSnippetCategories)[number];

export interface DefaultPromptSnippet {
  id: string;
  title: string;
  content: string;
  category: PromptSnippetCategory;
  createdAt?: string;
  updatedAt?: string;
}

export const promptSnippetCategoryOptions: Array<{
  value: 'all' | PromptSnippetCategory;
  label: string;
}> = [
  { value: 'all', label: '全部分类' },
  ...promptSnippetCategories.map((category) => ({ value: category, label: category }))
];

function createDefaultPromptGroup(
  idPrefix: string,
  category: PromptSnippetCategory,
  entries: Array<[title: string, content: string]>
): DefaultPromptSnippet[] {
  return entries.map(([title, content], index) => ({
    id: `default-${idPrefix}-${index + 1}`,
    title,
    content,
    category
  }));
}

